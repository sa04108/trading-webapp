import { describe, expect, it } from 'vitest';
import {
  isExecutionLimitation,
  summarizeExecutionWarnings,
} from '../../src/web/features/backtests/execution-warning-summary.js';

describe('summarizeExecutionWarnings', () => {
  it('한 건뿐인 과거 종목별 경고도 코드 없는 건수 문장으로 바꾼다', () => {
    expect(summarizeExecutionWarnings([
      '005930 매수 거부: 그날 거래정지·무거래로 매수할 수 없는 종목입니다.',
      '000660 매수 거부: 활성 멤버십 일정에 포함되지 않은 종목입니다 (전략 버그 안전망).',
      '123456 주문 거부/폐기: 상장폐지 경계를 넘어 재사용된 단축코드의 후속 봉에 체결할 수 없습니다.',
    ])).toEqual([
      '거래정지·무거래로 매수 거부된 종목 1건.',
      '활성 멤버십 일정 밖이라 매수 거부된 종목 1건 (전략 버그 안전망).',
      '상장폐지 경계를 넘어 재사용된 단축코드라 주문이 거부·폐기된 종목 1건. 후속 봉에는 체결하지 않았습니다.',
    ]);
  });

  it('현금 부족은 종목 수가 아니라 실제 거부 사건 수로 합친다', () => {
    expect(summarizeExecutionWarnings([
      '005930 매수 거부: 현금 부족 (2026-01-03T05:00:00.000Z)',
      '005930 매수 거부: 현금 부족 (2026-01-04T05:00:00.000Z)',
      '000660 매수 거부: 현금 부족 (2026-01-05T05:00:00.000Z)',
    ])).toEqual(['현금 부족으로 거부된 매수 주문 3건.']);
  });

  it('종목별 거부 경고는 중복 코드를 한 종목으로 센다', () => {
    expect(summarizeExecutionWarnings([
      '005930 매수 거부: 그날 거래정지·무거래로 매수할 수 없는 종목입니다.',
      '005930 매수 거부: 그날 거래정지·무거래로 매수할 수 없는 종목입니다.',
      '000660 매수 거부: 그날 거래정지·무거래로 매수할 수 없는 종목입니다.',
    ])).toEqual(['거래정지·무거래로 매수 거부된 종목 2건.']);
  });

  it('데이터셋 drift는 같은 코드의 여러 slice를 한 종목으로 센다', () => {
    expect(summarizeExecutionWarnings([
      '제출 이후 데이터가 변경된 종목이 있습니다: 005930(profile), 005930(market-cap), 000660(profile) — 결과가 제출 당시 데이터와 다를 수 있습니다.',
    ])).toEqual([
      '제출 이후 데이터가 변경된 종목 2건이 있습니다 — 결과가 제출 당시 데이터와 다를 수 있습니다.',
    ]);
  });

  it('잘린 대상 목록은 표시된 코드 수 대신 생산자가 기록한 전체 종목 수를 보존한다', () => {
    const warning = '동시 보유 종목 상한(5)에 걸려 매수 주문 38건이 폐기되었습니다 '
      + '— 대상 17종목: 000001, 000002, 000003, 000004, 000005, 000006, 000007, 000008, 000009, 000010 외 7종목. '
      + '그만큼 자본이 현금으로 남았습니다. 전략의 보유 종목 수를 상한 이하로 줄이거나 상한을 올리세요.';
    const [summary] = summarizeExecutionWarnings([warning]);
    expect(summary).toContain('매수 주문 38건');
    expect(summary).toContain('대상 17종목.');
    expect(summary).not.toContain('000001');
    expect(summary).not.toContain('외 7종목');
  });

  it('유동성 목록만 지우고 소수 비율·체결 건수·설명은 보존한다', () => {
    const warning = '유동성 체결 한도: 직전 거래 봉 거래량의 2.5%와 현재 체결 봉 총거래량 중 작은 수량까지 체결합니다. '
      + '매수 잔량은 폐기하고 매도 잔량은 다음 거래 봉에서 재시도합니다. '
      + '상장폐지 강제정산은 마지막 거래 종가 전량 정산 모델을 유지해 이 한도에서 제외합니다. '
      + '한도로 축소된 체결 시도 12건, 거부된 체결 시도 3건 — 대상 11종목: '
      + '000001, 000002, 000003, 000004, 000005, 000006, 000007, 000008, 000009, 000010 외 1종목.';
    const [summary] = summarizeExecutionWarnings([warning]);
    expect(summary).toContain('2.5%');
    expect(summary).toContain('축소된 체결 시도 12건, 거부된 체결 시도 3건');
    expect(summary).toContain('대상 11종목.');
    expect(summary).toContain('상장폐지 강제정산은 마지막 거래 종가 전량 정산 모델');
    expect(summary).not.toContain('000001');
  });

  it('상장폐지 목록은 제거하되 전체 건수와 손익 설명을 남긴다', () => {
    const warning = '상장폐지로 강제 청산한 종목 12건: '
      + '000001, 000002, 000003, 000004, 000005, 000006, 000007, 000008, 000009, 000010 외 2종목. '
      + '손익 합계 -1,234,567원. 체결가는 그 종목의 마지막 거래 가능 봉 종가이며, 정리매매가 있었다면 그 가격이 반영됩니다.';
    expect(summarizeExecutionWarnings([warning])).toEqual([
      '상장폐지로 강제 청산한 종목 12건. 손익 합계 -1,234,567원. '
        + '체결가는 그 종목의 마지막 거래 가능 봉 종가이며, 정리매매가 있었다면 그 가격이 반영됩니다.',
    ]);
  });

  it('이미 건수만 있는 새 문자열에는 두 번 적용해도 변화가 없다', () => {
    const reusedCodeWarning = '단축코드 재사용을 발행사별로 구분할 수 없어 첫 상장폐지 이후 가격 봉을 제외한 종목 '
      + '11건: 000001, 000002, 000003, 000004, 000005, 000006, 000007, 000008, 000009, 000010 외 1종목. '
      + '새 발행사의 수익 기회가 반영되지 않아 결과가 보수적일 수 있습니다.';
    expect(summarizeExecutionWarnings([reusedCodeWarning])).toEqual([
      '단축코드 재사용을 발행사별로 구분할 수 없어 첫 상장폐지 이후 가격 봉을 제외한 종목 '
        + '11건. 새 발행사의 수익 기회가 반영되지 않아 결과가 보수적일 수 있습니다.',
    ]);

    const warnings = [
      '현금 부족으로 거부된 매수 주문 3건.',
      '동시 보유 종목 상한(5)에 걸려 매수 주문 38건이 폐기되었습니다 — 대상 17종목. 그만큼 자본이 현금으로 남았습니다.',
      '상장폐지로 강제 청산한 종목 12건. 손익 합계 -1,234,567원.',
      '제출 이후 데이터가 변경된 종목 2건이 있습니다 — 결과가 제출 당시 데이터와 다를 수 있습니다.',
    ];
    expect(summarizeExecutionWarnings(summarizeExecutionWarnings(warnings))).toEqual(warnings);
  });

  it('전역 설명과 알 수 없는 경고는 숫자를 해석하거나 내용을 바꾸지 않는다', () => {
    const warnings = [
      '이 백테스트가 보정하지 않는 것: 배당. 손절·익절은 종가로만 판정합니다.',
      '임의 모델 경고: 임계값 12.75%, 관측일 2026-03-04, 최소 금액 005930원.',
    ];
    expect(summarizeExecutionWarnings(warnings)).toEqual(warnings);
  });
});

describe('isExecutionLimitation', () => {
  it.each([
    '이 백테스트가 보정하는 것: 시점별 유니버스 선정.',
    '이 백테스트가 보정하지 않는 것: 배당.',
    '유동성 체결 한도: 직전 거래 봉 거래량의 2.5%까지 체결합니다.',
    '재무 데이터는 공시 시점 기준입니다. 계정이 일부만 공시될 수 있습니다.',
    '선택한 기간이 최근이라 아직 DART 에 공시되지 않은 자본변동이 있을 수 있습니다.',
    '이 실행 구간에는 거래불가일 정보가 없습니다 — 다시 실행하세요.',
    'EMA 추세 스위치: 상관 그룹 워밍업 부족 (필요 60봉, 확보 최대 42봉).',
  ])('알려진 모델 설명을 제한사항으로 분류한다: %s', (warning) => {
    expect(isExecutionLimitation(warning)).toBe(true);
  });

  it('분류되지 않은 실행 경고는 실행 범주에 남긴다', () => {
    expect(isExecutionLimitation('기간 종료로 체결되지 않은 주문 3건이 폐기되었습니다.')).toBe(false);
  });
});
