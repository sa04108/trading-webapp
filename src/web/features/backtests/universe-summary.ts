/**
 * 백테스트 설명 줄의 유니버스 표기 — 데이터셋 이름과 종목 수만 적는다.
 *
 * 종목을 나열하지 않는 이유: 백테스트는 종목을 고르지 않고 데이터셋을 고른다 (D-038).
 * 유니버스를 정하는 것이 데이터셋이므로 설명이 가리켜야 하는 것도 데이터셋이다.
 * 200종목 중 앞 5개를 적는 표기는 나머지 195개를 감추면서 그 5개가 왜 앞에 왔는지도
 * (코드순일 뿐이다) 알려주지 않았다. 전체 목록은 결과 화면의 거래 내역 종목 필터와
 * 종목별 성과 표에 있다.
 *
 * 종목 수는 **실행된 요청**에서 센다 — 데이터셋의 현재 종목 수가 아니다. 실행 후
 * 데이터셋에 종목이 더해지거나 빠질 수 있고, 그때 카드가 지금 개수를 적으면 그 백테스트
 * 가 돌지 않은 종목까지 센 셈이 된다.
 */

/**
 * '코스피 대형주 · 187종목'. 이름을 찾지 못하면 id 를 쓴다.
 *
 * 이름은 지금 카탈로그에서 찾으므로 실행 뒤 이름이 바뀌면 새 이름으로 보인다. 실행을
 * 특정하는 값은 `datasetId` 고 그것은 재현 정보 카드에 그대로 남는다. 데이터셋을
 * 지워도 설명이 비지 않게 id 를 대신 적는다 — 어느 데이터셋이었는지는 남아야 한다.
 */
export function formatUniverseSummary(
  datasetName: string | null,
  datasetId: string,
  symbolCount: number,
): string {
  return `${datasetName ?? datasetId} · ${symbolCount}종목`;
}
